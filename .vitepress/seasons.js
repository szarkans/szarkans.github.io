// Сезоны Кошкокрафта — единственное место, где они описаны.
// Отсюда строится страница-вход /history/ (лента сезонов с обложками).
//
// ДОБАВЛЯЕШЬ СЕЗОН: сначала создай папку `history/<N>season/` со страницей
// `<N>season.md`, потом добавь запись сюда. В обратном порядке карточка будет
// вести в никуда — правда, сборка теперь на этом падает и скажет, чего не
// хватает (`scripts/check-seasons.mjs`).
//
// 🛑 МЕНЯЕШЬ ДАТУ ИЛИ ВЕРСИЮ — правишь ДВА места. Здесь для ленты сезонов,
// и блок `::: tip Версии и даты сезона` в самой статье `history/<N>season/
// <N>season.md`. Это разные тексты, и они уже разошлись: у 4 сезона в статье
// «1.19.3 - ???», здесь «С версии 1.19.3». Свести их в один источник пока
// некому — статьи писались руками задолго до этого файла.
//
// ─────────────────────────────────────────────────────────────────────────
// ПОЛЯ
//
//   n         Номер сезона. По нему же собираются адреса страниц
//             (/history/9season/9season и /history/9season/album)
//             и путь к обложке — так что менять больше ничего не нужно.
//
//   from      Дата начала в формате ГОД-МЕСЯЦ-ДЕНЬ: '2026-08-01'.
//   to        Дата конца в том же формате. У идущего сезона её нет.
//             Из этих двух дат сами считаются и подпись «01.08.2026 — …»,
//             и длительность сезона. Руками писать длительность не надо.
//
//   versions  Строка как есть, целиком: 'Версии 1.20.1 — 1.20.4'
//             или 'Версия 1.21.1'. Что напишешь, то и покажется.
//
//   fuzzyEnd  Если точного дня конца никто не помнит. Пишешь сюда то, что
//             показать вместо даты: 'январь 2023'. Длительность тогда
//             станет осторожной — «около 7 месяцев».
//
//   current   Сезон идёт прямо сейчас. Вместо даты конца — зелёная точка
//             «Сезон идёт прямо сейчас», как в статусе сервера на главной.
//
//   redacted  Сезон, которого «не было». Обложка обесцвечена, даты замазаны
//             квадратиками. Сейчас так помечен только 7-й.
//
// ─────────────────────────────────────────────────────────────────────────
// ОБЛОЖКИ
//
// Лежат в  public/assets/history/covers/  и называются строго по номеру:
// 1season.webp, 2season.webp, 3season.webp …
//
// ЧТОБЫ ПОМЕНЯТЬ ОБЛОЖКУ: положи свой файл с тем же именем поверх старого.
// Ни этот файл, ни код трогать не надо — картинка подхватится сама.
//
// Какая картинка подойдёт:
//   • широкий кадр, примерно как экран (16:9), от 1000 пикселей в ширину;
//   • формат .webp (обычный скриншот в .png тоже заработает — но тяжелее,
//     прогнать через `npm run optimize-images` не помешает);
//   • важное — в правой половине кадра: на широком экране левая половина
//     уходит под затемнение, на ней лежат номер сезона, даты и кнопки;
//   • не слишком светлая снизу — по низу на телефоне идёт тот же текст.
//
// Нет обложки у сезона — ничего не сломается, карточка просто будет без
// картинки (так сейчас выглядит идущий 8-й сезон).

